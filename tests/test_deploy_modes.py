"""deploy/deploy.sh: one setting chooses dev, host or k3s, and only k3s may touch a cluster.

Generated by traction-control's scaffold_deployment_modes.py (kind: service). The script runs against stub
commands that record every call, so nothing here needs systemd, podman or a cluster, which is the point: a
developer without K3s must be able to run and test magneto. Keep these tests passing as you fill in deploy/k3s/.
"""

from __future__ import annotations

import os
import shutil
import subprocess
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
DEPLOY = REPO / "deploy" / "deploy.sh"
UNIT = "magneto-web.service"
K3S_STEPS = ["build-image.sh", "apply.sh", "verify.sh"]
EXTRA_STUBS = ["bridge.sh", "rpc-proxy.sh"]
SOURCES = ["src", "pyproject.toml", "README.md"]
PREFIX = "MAGNETO"
STATE_NAME = "magneto"


def _stub(path: Path, log: Path, name: str, body: str = "") -> None:
    path.write_text(f'#!/usr/bin/env bash\necho "{name} $*" >> "{log}"\n{body}\n')
    path.chmod(0o755)


@pytest.fixture
def sandbox(tmp_path):
    """A PATH of recording stubs, a stub k3s directory, and private state and unit folders."""
    bin_dir, k3s, log = tmp_path / "bin", tmp_path / "k3s", tmp_path / "calls.log"
    bin_dir.mkdir()
    k3s.mkdir()
    for name, body in {
        "kubectl": "exit 99",
        "podman": "exit 99",
        "curl": "exit 22",
        "systemctl": 'case "$*" in *is-active*) echo inactive; exit 3 ;; *is-enabled*) echo disabled; exit 1 ;; esac',
    }.items():
        _stub(bin_dir / name, log, name, body)
    for step in [*K3S_STEPS, *EXTRA_STUBS]:
        _stub(k3s / step, log, step)
    shutil.copy(REPO / "deploy" / "k3s" / "env_value.py", k3s / "env_value.py")
    env = {
        **os.environ,
        "PATH": f"{bin_dir}:{os.environ['PATH']}",
        f"{PREFIX}_K3S_DIR": str(k3s),
        f"{PREFIX}_DEPLOY_CONFIG": str(tmp_path / "deploy.local.env"),
        f"{PREFIX}_UNITS_DIR": str(tmp_path / "units"),
        "XDG_STATE_HOME": str(tmp_path / "state"),
    }
    env.pop(f"{PREFIX}_DEPLOY_MODE", None)
    return env, log, tmp_path


def run(env, *args):
    return subprocess.run(
        ["bash", str(DEPLOY), *args], env=env, capture_output=True, text=True, timeout=60
    )


def calls(log: Path) -> list[str]:
    return log.read_text().splitlines() if log.exists() else []


def names(log: Path) -> list[str]:
    return [c.split()[0] for c in calls(log)]


def cluster_ready(tmp_path):
    """The registry answers and kubectl succeeds."""
    log = tmp_path / "calls.log"
    _stub(tmp_path / "bin" / "curl", log, "curl")
    _stub(tmp_path / "bin" / "kubectl", log, "kubectl")


def marker(tmp_path, value="k3s"):
    folder = tmp_path / "state" / STATE_NAME
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "deploy-mode").write_text(value + "\n")
    return folder / "deploy-mode"


def marker_path(tmp_path) -> Path:
    return tmp_path / "state" / STATE_NAME / "deploy-mode"


